conn = sqlite3.connect(DB_PATH)
conn.row_factory = sqlite3.Row
cur = conn.cursor()

cur.execute('SELECT id FROM questions ORDER BY id')
question_ids = [row['id'] for row in cur.fetchall()]
expected = list(range(1, 55))
if question_ids != expected:
    raise RuntimeError(f'Unexpected question ids: {question_ids}')

for qid in expected:
    payload = question_payloads[qid]
    cur.execute(
        'UPDATE questions SET question_text = ?, category = ?, image_url = NULL, points = 1 WHERE id = ?',
        (payload['question_text'], payload['category'], qid),
    )

    cur.execute('SELECT id FROM answers WHERE question_id = ? ORDER BY id', (qid,))
    answer_ids = [row['id'] for row in cur.fetchall()]
    if len(answer_ids) != 4:
        raise RuntimeError(f'Question {qid} has {len(answer_ids)} answers, expected 4')

    for answer_id, answer_payload in zip(answer_ids, payload['answers']):
        cur.execute(
            'UPDATE answers SET answer_text = ?, is_correct = ?, explanation = ? WHERE id = ?',
            (
                answer_payload['text'],
                1 if answer_payload['is_correct'] else 0,
                answer_payload['explanation'],
                answer_id,
            ),
        )

# Remove broken/temporary admin tests without questions (e.g. debug CRUD garbage)
cur.execute(
    '''
    SELECT t.id, t.title, COUNT(q.id) AS question_count
    FROM admin_tests t
    LEFT JOIN admin_test_questions q ON q.test_id = t.id
    WHERE t.is_legacy = 0
    GROUP BY t.id, t.title
    '''
)
for row in cur.fetchall():
    title = row['title'] or ''
    has_many_question_marks = title.count('?') >= 3
    if row['question_count'] == 0 and (has_many_question_marks or 'CRUD' in title.upper()):
        test_id = row['id']
        cur.execute('DELETE FROM admin_assignments WHERE test_id = ?', (test_id,))
        cur.execute('DELETE FROM admin_test_questions WHERE test_id = ?', (test_id,))
        cur.execute('DELETE FROM admin_tests WHERE id = ?', (test_id,))

# Ensure category normalized for remaining questions
cur.execute("UPDATE questions SET category='Дорожные знаки и разметка' WHERE category='Дорожные знаки'")

