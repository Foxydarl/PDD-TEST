RNG = random.Random(42)


def _pick_wrong(values: List[str], current: str, count: int = 3) -> List[str]:
    pool = [value for value in values if value != current]
    return RNG.sample(pool, count)


def _validate_question(question: Dict) -> None:
    answers = question.get("answers", [])
    if len(answers) != 4:
        raise ValueError(f"Question must contain exactly 4 answers: {question['question_text']}")
    correct_count = sum(1 for answer in answers if answer.get("is_correct"))
    if correct_count != 1:
        raise ValueError(f"Question must contain exactly 1 correct answer: {question['question_text']}")


