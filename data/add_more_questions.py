def main() -> None:
    if not DB_PATH.exists():
        raise FileNotFoundError(f"Database not found: {DB_PATH}")

    questions_to_add: List[Dict] = []
    questions_to_add.extend(build_definition_questions())
    questions_to_add.extend(build_sign_questions())
    questions_to_add.extend(build_rule_questions())

    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    cur = conn.cursor()

    cur.execute("PRAGMA table_info(questions)")
    columns = {row["name"] for row in cur.fetchall()}
    has_language = "language" in columns

    cur.execute("SELECT COALESCE(NULLIF(language, ''), 'ru') as language, question_text FROM questions" if has_language else "SELECT 'ru' as language, question_text FROM questions")
    existing = {(row["language"], row["question_text"].strip()) for row in cur.fetchall()}

    inserted = 0
    skipped = 0
    for question in questions_to_add:
        key = (question["language"], question["question_text"].strip())
        if key in existing:
            skipped += 1
            continue

        if has_language:
            cur.execute(
                """
                INSERT INTO questions (question_text, category, language, image_url, points)
                VALUES (?, ?, ?, NULL, 1)
                """,
                (question["question_text"], question["category"], question["language"]),
            )
        else:
            cur.execute(
                """
                INSERT INTO questions (question_text, category, image_url, points)
                VALUES (?, ?, NULL, 1)
                """,
                (question["question_text"], question["category"]),
            )
        question_id = cur.lastrowid

        for answer in question["answers"]:
            cur.execute(
                """
                INSERT INTO answers (question_id, answer_text, is_correct, explanation)
                VALUES (?, ?, ?, ?)
                """,
                (
                    question_id,
                    answer["answer_text"],
                    1 if answer["is_correct"] else 0,
                    answer["explanation"],
                ),
            )

        existing.add(key)
        inserted += 1

    conn.commit()

    cur.execute("SELECT COUNT(*) AS total FROM questions")
    total_questions = int(cur.fetchone()["total"])
    cur.execute("SELECT COUNT(*) AS total FROM answers")
    total_answers = int(cur.fetchone()["total"])

    print(f"Inserted questions: {inserted}")
    print(f"Skipped duplicates: {skipped}")
    print(f"Total questions: {total_questions}")
    print(f"Total answers: {total_answers}")

    cur.execute(
        """
        SELECT category, COUNT(*) AS total
        FROM questions
        GROUP BY category
        ORDER BY total DESC, category
        """
    )
    print("By category:")
    for row in cur.fetchall():
        print(f"  - {row['category']}: {row['total']}")

    conn.close()


if __name__ == "__main__":
    main()
