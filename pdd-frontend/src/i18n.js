export function translate(language, key, params = {}) {
  const locale = messages[language] || messages[DEFAULT_LANGUAGE]
  const template = locale[key] ?? messages[DEFAULT_LANGUAGE][key] ?? key
  return template.replace(/\{(\w+)\}/g, (_, name) => {
    if (params[name] === undefined || params[name] === null) {
      return ''
    }
    return String(params[name])
  })
}

const ACCOUNT_LANGUAGE_STORAGE_KEY = 'pdd_language_by_account'

function safeParse(rawValue, fallback) {
  if (!rawValue) return fallback
  try {
    return JSON.parse(rawValue)
  } catch (error) {
    return fallback
  }
}

function normalizeLanguage(rawValue) {
  const supported = new Set(LANGUAGE_OPTIONS.map((item) => item.value))
  if (supported.has(rawValue)) {
    return rawValue
  }
  return DEFAULT_LANGUAGE
}

export function getAccountLanguage(accountId) {
  if (!accountId) return DEFAULT_LANGUAGE
  const map = safeParse(localStorage.getItem(ACCOUNT_LANGUAGE_STORAGE_KEY), {})
  return normalizeLanguage(map[accountId])
}

export function setAccountLanguage(accountId, language) {
  if (!accountId) return
  const map = safeParse(localStorage.getItem(ACCOUNT_LANGUAGE_STORAGE_KEY), {})
  map[accountId] = normalizeLanguage(language)
  localStorage.setItem(ACCOUNT_LANGUAGE_STORAGE_KEY, JSON.stringify(map))
}

